export const BINGO_LINES = [
  ...Array.from({length:5}, (_,r) => Array.from({length:5}, (_,c) => r*5+c)),
  ...Array.from({length:5}, (_,c) => Array.from({length:5}, (_,r) => r*5+c)),
  [0,6,12,18,24], [4,8,12,16,20],
];
export function completeLines(stamped) {
  const set = new Set(stamped);
  return BINGO_LINES.filter((line) => line.every((idx) => set.has(idx)));
}
